import isPhoneNumberValid from '../isPhoneNumberValid';

describe('Verify Phone numbers', () => {
  test.each`
    phoneNumber
    ${'079 765 43 21'}
    ${'0041(0)79 765 43 21'}
    ${'+4179 765 43 21'}
    ${'++4179 765 43 21'}
    ${'027 951 41 12'}
    ${'063 876 54 32'}
    ${'063 876 54 32 123'}
    ${'+41(0)289876543'}
    ${'0783268674'}
    ${'0041783268674'}
    ${'+41783268674'}
    ${'+33783268674'}
    ${'+49783268674'}
    ${'+43783268674'}
    ${'+39783268674'}
    ${'++41783268674'}
    ${'++41(0)783268674'}
    ${'+4917612345678'}
    ${'041783268674'}
    ${'04178326867'}
    ${'0795870603'}
    ${'0791112233'}
    ${'0041791112233'}
    ${'0796786050'}
    ${'079 678 60 50'}
  `('phone number is valid', ({ phoneNumber }) => {
    expect(isPhoneNumberValid(phoneNumber)).toBeTruthy();
  });
  test.each`
    phoneNumber
    ${'061 214 12 1'}
    ${'12332124'}
    ${'+23 44 123'}
    ${'00783268674'}
    ${'+041783268674'}
    ${'00041783268674'}
    ${'+++41783268674'}
    ${'(0)783268674'}
    ${'++410783268674'}
    ${'1783268674'}
    ${'41781234567'}
  `('phone number is not valid', ({ phoneNumber }) => {
    expect(isPhoneNumberValid(phoneNumber)).toBeFalsy();
  });
});
